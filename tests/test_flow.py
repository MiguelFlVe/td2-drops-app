import json, math
from playwright.sync_api import sync_playwright
import os
HERE=os.path.dirname(os.path.abspath(__file__))+'/'
URL=os.environ.get('TD2_URL','http://127.0.0.1:8772/index.html')
SP=os.environ.get('TD2_OUT', HERE+'out/'); os.makedirs(SP, exist_ok=True)
errors=[]; dialogs=[]
def ok(c,m): print(('PASS ' if c else 'FAIL ')+m)
def pct(x): return float(x.replace('%','').replace(',',''))
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2)
    pg=ctx.new_page(); pg.on('pageerror', lambda e: errors.append(str(e)))
    def on_d(d): dialogs.append(d.message); d.accept()
    pg.on('dialog', on_d)
    pg.goto(URL)
    L='#log'
    btn=lambda name, scope=L: pg.locator(scope).get_by_role('button', name=name, exact=True).first
    steps=lambda scope=L: pg.evaluate(f"[...document.querySelectorAll('{scope} .step')].map(s=>s.className.replace('step ',''))")
    ok(steps()==['open','locked','locked','locked'], 'initial: only step 1 open %s'%steps())
    ok('Log drop' in pg.locator('nav.tabs').inner_text() and 'Drop log & roll odds' in pg.locator('header').inner_text(), 'UI in English')
    # --- Brand Named kneepads (Kneepads -> Česká Výroba -> Turmoil) ---
    btn('Brand Set').click()
    ok(steps()==['done','open','locked','locked'], 'type chosen: step 2 open %s'%steps())
    ok(pg.locator(L+' select').count()==0, 'set selector hidden until the slot is chosen')
    btn('Kneepads').click()
    ok(steps()==['done','open','locked','locked'], 'slot without set: step 2 still open, rarity locked')
    ok(pg.locator(L+' .step').nth(2).locator('.locked-hint').inner_text()=='Choose the brand first.', 'rarity hint asks for the brand')
    ok(pg.locator('#logbar .missing').inner_text()=='Missing: brand', 'missing: brand')
    pg.locator(L+' select').first.select_option('Česká Výroba s.r.o.')
    ok(steps()[:3]==['done','done','open'], 'set chosen: step 3 open')
    ok(pg.locator(L+' .step').nth(1).locator('.step-s').inner_text()=='Kneepads · Česká Výroba s.r.o.', 'step 2 summary shows slot · set')
    btn('Named').click()
    ok(pg.locator(L).get_by_text('Bewildered').count()>=1, 'single Named auto-selected (Turmoil) with its unique attribute')
    ok('Turmoil' in pg.locator(L+' .step').nth(2).inner_text(), 'step 3 summary shows Turmoil')
    labels=pg.locator(L+' .step').nth(3).locator('.lbl > span:first-child').all_inner_texts()
    ok(labels==['CORE ATTRIBUTE','UNIQUE ATTRIBUTE','ATTRIBUTE','NOTE'] or labels==['Core attribute','Unique attribute','Attribute','Note'], 'named kneepads: core + locked attr + 1 attribute: %s'%labels)
    btn('Armor').click(); btn('Health').click()
    ok(pg.locator('#logbar .missing').inner_text()=='Ready to save', 'ready to save named kneepads')
    pg.screenshot(path=SP+'v2-01-log-named.png', full_page=True)
    pg.locator('#logbar button').click()
    # after save: item kept, roll cleared
    ok(steps()[:3]==['done','done','done'] and pg.locator('#logbar .missing').inner_text().startswith('Missing'), 'after save: item kept, roll reset')
    # --- reset behaviour ---
    pg.locator(L+' select').first.select_option('Gila Guard')
    ok(steps()==['done','done','open','locked'] and btn('Kneepads').get_attribute('aria-pressed')=='true', 'changing the set keeps the slot, resets rarity: %s'%steps())
    btn('Mask').click()
    ok(steps()==['done','open','locked','locked'] and pg.locator(L+' select').first.input_value()=='', 'changing the slot resets the set: %s'%steps())
    pg.locator(L+' select').first.select_option('Gila Guard'); btn('Named').click()
    ok(pg.locator(L).get_by_role('button', name='Chill Out', exact=False).count()==1 and pg.locator(L).get_by_role('button', name='Nightwatcher', exact=False).count()==1, 'two Named masks offered for Gila Guard')
    ok(steps()[2]=='open', 'step 3 open until one is picked')
    pg.locator(L).get_by_role('button', name='Nightwatcher', exact=False).click()
    ok(steps()[2]=='done', 'picked Nightwatcher')
    # Brand slot without named
    pg.locator(L+' select').first.select_option('Airaldi Holdings')
    ok(pg.locator(L).get_by_role('button', name='Named (none)').is_disabled(), 'Named disabled when brand+slot has none')
    # --- Brand High End chest ---
    btn('Chest').click(); pg.locator(L+' select').first.select_option('Airaldi Holdings'); btn('High End').click()
    tal=pg.locator(L+' .step').nth(3).locator('select')
    ok(tal.locator('option').count()-1==24, 'HE chest: 24 chest talents')
    btn('Weapon Damage').click(); btn('Critical Hit Chance').click(); btn('Critical Hit Damage').click(); tal.select_option('Glass Cannon')
    pg.locator('#logbar button').click()
    # --- Gear Set chest ---
    btn('Gear Set').click()
    ok(steps()==['done','open','locked','locked'], 'changing the type resets everything after it')
    btn('Chest').click()
    ok(steps()[2]=='locked', 'gear set: rarity waits for the set')
    pg.locator(L+' select').first.select_option("Striker's Battlegear")
    ok(steps()[2]=='done', 'gear set: rarity auto-complete')
    ok(pg.locator(L).get_by_text('Gear Set talent (comes with the set)').count()==1, 'gear set chest: talent locked')
    btn('Weapon Damage').click(); btn('Weapon Handling').click()
    pg.locator('#logbar button').click()
    # --- Weapons ---
    btn('Weapon').click()
    btn('Assault Rifle').click()
    ok(pg.locator(L+' select').count()==0 and steps()[1]=='done' and pg.locator(L+' .step').nth(1).locator('.step-s').inner_text()=='Assault Rifle', 'weapon: no set selector, step 2 done')
    btn('High End').click()
    st4=pg.locator(L+' .step').nth(3)
    attrs=st4.locator('.chip').all_inner_texts()
    ok('Damage to Health' not in attrs and len(attrs)==5, 'AR attribute pool excludes core 2 (Damage to Health): %s'%attrs)
    ok(st4.locator('select option').count()-1==34, 'AR talent pool size = %d'%(st4.locator('select option').count()-1))
    btn('Critical Hit Chance').click(); st4.locator('select').select_option('Optimist'); pg.locator('#logbar button').click()
    btn('Named').click()
    sel3=pg.locator(L+' .step').nth(2).locator('select')
    ok(sel3.locator('option').count()-1==22, '22 Named ARs in a dropdown')
    sel3.select_option('Lexington')
    ok(pg.locator(L+' .step').nth(3).locator('.perk').inner_text().endswith('+1,782 Base Damage') and pg.locator(L+' .step').nth(3).locator('select').count()==0, 'Named weapon: unique perk locked, no talent picker')
    btn('Headshot Damage').click(); pg.locator('#logbar button').click()
    ok(pg.locator('#count').inner_text()=='5 drops', 'five drops saved')
    data=json.loads(pg.evaluate("localStorage.getItem('td2-drop-tracker-v1')"))
    d=data['drops']
    ok(d[0]=={**d[0], 'cat':'brand','set':'Česká Výroba s.r.o.','slot':'Kneepads','rarity':'Named','named':'Turmoil','core':'Armor','attrs':['Health'],'talent':None}, 'named drop stored correctly')
    ok(d[1]['talent']=='Glass Cannon' and d[1]['attrs']==['Critical Hit Chance','Critical Hit Damage'] and d[1]['rarity']=='High End', 'HE chest stored correctly')
    ok(d[2]['cat']=='gear' and d[2]['rarity']=='Gear Set' and d[2]['talent'] is None, 'gear set stored correctly')
    ok(d[3]['cat']=='weapon' and d[3]['core'] is None and d[3]['talent']=='Optimist', 'HE weapon stored correctly')
    ok(d[4]['named']=='Lexington' and d[4]['talent'] is None, 'named weapon stored correctly')
    # --- History ---
    pg.locator('nav.tabs button[data-go="hist"]').click()
    titles=pg.locator('.drop-title').all_inner_texts()
    ok(titles==['Lexington','High End Assault Rifle',"Striker's Battlegear Chest",'Airaldi Holdings Chest','Turmoil'], 'history titles %s'%titles)
    ok(pg.locator('.tag.perk-tag').count()==3, 'perk tags for Lexington, Striker chest, Turmoil')
    pg.screenshot(path=SP+'v2-02-hist.png', full_page=True)
    ctx.close()
    b.close()
print('ERRORS', errors)
print('DIALOGS', dialogs)
