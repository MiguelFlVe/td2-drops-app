#!/usr/bin/env python3
"""Turns a Drops TD2 backup (History → Save a copy) into the app's bundled base data.

Usage:
    python3 tools/actualizar_datos_base.py backup.json --label "Red Horizon season"

Writes app/src/main/assets/base-data.js. For privacy (the repository is public) it removes each drop's
note and date; it keeps the id so drops a user already has aren't counted twice. Backups from older
(Spanish) versions are accepted too: the app converts them when it loads.
"""
import argparse, json, pathlib, sys

SKIP = {'note', 'ts'}
TARGET = pathlib.Path(__file__).resolve().parent.parent / 'app' / 'src' / 'main' / 'assets' / 'base-data.js'
CATS = {'brand', 'gear', 'weapon', 'Equipo', 'Arma'}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('backup', nargs='?', help='.json file exported from the app (omit for no base data)')
    ap.add_argument('--label', default='Base data', help='name shown in the app')
    ap.add_argument('--out', default=str(TARGET), help='base-data.js path to write')
    a = ap.parse_args()
    drops = []
    if a.backup:
        data = json.loads(pathlib.Path(a.backup).read_text(encoding='utf-8-sig'))
        items = data if isinstance(data, list) else data.get('drops', [])
        seen = set()
        for d in items:
            if not isinstance(d, dict) or d.get('cat') not in CATS or not (d.get('slot') or d.get('sub')):
                continue
            if d.get('id') in seen:
                continue
            seen.add(d.get('id'))
            drops.append({k: v for k, v in d.items() if k not in SKIP and v is not None})
    out = pathlib.Path(a.out)
    out.write_text(
        '/* Drops TD2 base data. Generated by tools/actualizar_datos_base.py — do not edit by hand. */\n'
        'window.TD2_BASE = ' + json.dumps({'label': a.label, 'drops': drops}, ensure_ascii=False, separators=(',', ':')) + ';\n',
        encoding='utf-8')
    print(f'{out.name}: {len(drops)} drops · "{a.label}"')

if __name__ == '__main__':
    sys.exit(main())
